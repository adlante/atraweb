def generate():
    for rel_path, data in PAGES.items():
        full_path = os.path.join(TEMPLATES_DIR, rel_path)
        os.makedirs(os.path.dirname(full_path), exist_ok=True)

        # ساخت HTML کارت‌ها
        cards_html = ""
        for card_title, card_text, tags in data['cards']:
            tags_html = "".join([f'<span class="rich-feature-tag">{t}</span>' for t in tags])
            cards_html += f"""
                <div class="rich-pillar-card">
                    <h3 class="rich-pillar-title">{card_title}</h3>
                    <p class="rich-pillar-text">{card_text}</p>
                    <div class="rich-feature-tags">{tags_html}</div>
                </div>
            """

        # ساخت جدول
        th_html = "".join([f"<th>{h}</th>" for h in data['table_headers']])
        tr_html = ""
        for row in data['table_rows']:
            tds = "".join([f"<td>{c}</td>" for c in row])
            tr_html += f"<tr>{tds}</tr>"

        # ساخت سوالات متداول و اسکیما
        faqs_html = ""
        faq_schema_items = []
        for q, a in data['faqs']:
            faqs_html += f"""
                <div class="faq-item-box">
                    <h3 class="faq-question-title"><span>✦</span> {q}</h3>
                    <p class="faq-answer-text">{a}</p>
                </div>
            """
            faq_schema_items.append(f"""{{
              "@type": "Question",
              "name": "{q}",
              "acceptedAnswer": {{
                "@type": "Answer",
                "text": "{a}"
              }}
            }}""")
        faq_schema = ",\n".join(faq_schema_items)

        # تزریق کامل داده‌ها به قالب
        content = HTML_TEMPLATE.format(
            title=data['title'],
            meta_desc=data['meta_desc'],
            keywords=data['keywords'],
            badge=data['badge'],
            h1=data['h1'],
            lead=data['lead'],
            pillar_title=data['pillar_title'],
            cards_html=cards_html,
            th_html=th_html,
            tr_html=tr_html,
            faqs_html=faqs_html,
            faq_schema=faq_schema,
            cta_h=data['cta_h'],
            cta_p=data['cta_p'],
            cta_btn=data['cta_btn'],
        )

        with open(full_path, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"✅ بازنویسی کامل و فول‌سئو: {rel_path}")

    print("\n🚀 تمام صفحات لینک‌شده در فوتر با متون عمیق و اسکیمای گوگل به‌روزرسانی شدند!")

if __name__ == '__main__':
    generate()